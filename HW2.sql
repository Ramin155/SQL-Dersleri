-- TASK 1
SELECT JOB_ID, COUNT(FIRST_NAME) ISCI_SAYI, FLOOR(AVG(SALARY)) ORTA_MAAS 
FROM HR.EMPLOYEES
GROUP BY JOB_ID
ORDER BY ISCI_SAYI DESC;

-- TASK 2
SELECT DEPARTMENT_ID, MIN(SALARY) MIN_MAAS, MAX(SALARY) MAX_MAAS 
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
ORDER BY DEPARTMENT_ID;

-- TASK 3
SELECT D.DEPARTMENT_NAME, L.CITY 
FROM HR.DEPARTMENTS D
LEFT JOIN HR.LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID;

-- TASK 4
SELECT JOB_ID, SUM(SALARY) MAAS_CEMI 
FROM HR.EMPLOYEES
GROUP BY JOB_ID
HAVING MAAS_CEMI > 50000
ORDER BY MAAS_CEMI DESC;

-- TASK 5
SELECT MANAGER_ID, COUNT(FIRST_NAME) ISCI_SAYI 
FROM HR.EMPLOYEES
WHERE COMMISSION_PCT IS NOT NULL
GROUP BY MANAGER_ID
HAVING ISCI_SAYI > 5;

-- TASK 6
SELECT L.CITY, COUNT(D.DEPARTMENT_ID) SOBE_SAYI 
FROM HR.LOCATIONS L
LEFT JOIN HR.DEPARTMENTS D ON L.LOCATION_ID = D.LOCATION_ID
GROUP BY L.CITY
ORDER BY SOBE_SAYI DESC;

-- TASK 7
SELECT E.FIRST_NAME, E.LAST_NAME, D.DEPARTMENT_NAME
FROM HR.EMPLOYEES E
FULL JOIN HR.DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
WHERE E.FIRST_NAME IS NULL OR E.LAST_NAME IS NULL OR D.DEPARTMENT_ID IS NULL;

-- TASK 8
SELECT D.DEPARTMENT_NAME, COUNT(E.FIRST_NAME) AS ISCI_SAYI 
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
HAVING ISCI_SAYI > 3;

-- DEPARTMENT_ID APPEARS IN BOTH TABLES, SO WE HAVE TO WRITE NAME/ALIAS OF THE TABLE NEXT TO THEM 
-- HAVING INSTEAD OF WHERE CAUSE OF GROUP BY
-- COUNT FIRST_NAME INSTEAD OF *, TO NOT INCLUDE NULLS


-- TASK 9
SELECT D.DEPARTMENT_NAME, J.JOB_TITLE, COUNT(E.FIRST_NAME) ISCI_SAYI, CEIL(AVG(E.SALARY)) ORTA_MAAS
FROM HR.DEPARTMENTS D
LEFT JOIN HR.EMPLOYEES E ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
LEFT JOIN HR.JOBS J ON E.JOB_ID = J.JOB_ID
GROUP BY D.DEPARTMENT_NAME, J.JOB_TITLE
HAVING ISCI_SAYI >= 3
ORDER BY D.DEPARTMENT_NAME, ISCI_SAYI DESC;

-- TASK 10
SELECT E.EMPLOYEE_ID, E.FIRST_NAME, E.LAST_NAME, COUNT(J.EMPLOYEE_ID) KECMIS_VEZIFE_SAYI 
FROM HR.JOB_HISTORY J
FULL JOIN HR.EMPLOYEES E 
ON J.EMPLOYEE_ID = E.EMPLOYEE_ID
GROUP BY E.EMPLOYEE_ID, E.FIRST_NAME, E.LAST_NAME
ORDER BY KECMIS_VEZIFE_SAYI DESC;